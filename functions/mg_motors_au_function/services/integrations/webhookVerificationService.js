'use strict';

const crypto = require('crypto');
const logger = require('../../utils/logger');
const integrationAuthService = require('./integrationAuthService');
const { signingSecretFingerprint } = require('./fusionReturnChannelProof');
const { getSharedWebhookConfig, isFusionInboundV2Enabled } = require('../../config/env');

/**
 * webhookVerificationService.js
 * -----------------------------------------------------------------------
 * Authenticates inbound dealer-CRM webhooks. Supports HMAC signature
 * (preferred) and static bearer/API-key fallback, per integration config.
 * Never logs the secret or the raw signature header value on failure —
 * only a boolean result and a safe error code.
 *
 * Local-only bypass is opt-in through ALLOW_INSECURE_WEBHOOKS=true. It is
 * deliberately rejected in production so a forgotten test flag cannot
 * expose customer webhooks.
 */

const ALLOW_INSECURE_WEBHOOKS =
  process.env.ALLOW_INSECURE_WEBHOOKS === 'true' && process.env.NODE_ENV !== 'production';

function timingSafeEqual(a, b) {
  const bufA = Buffer.from(a || '', 'utf8');
  const bufB = Buffer.from(b || '', 'utf8');
  if (bufA.length !== bufB.length) return false;
  return crypto.timingSafeEqual(bufA, bufB);
}

function computeHmac(secret, rawBody) {
  return crypto.createHmac('sha256', secret).update(rawBody).digest('hex');
}

/**
 * Zoho's Notification API limits the callback token to 50 characters.
 * Credential secrets generated by this application historically used 64
 * hexadecimal characters, so sending the stored secret directly made watch
 * registration fail with INVALID_DATA. Use a domain-separated, deterministic
 * 48-character token instead; the credential itself never leaves our store.
 */
function deriveZohoWatchToken(secret) {
  if (!secret) return '';
  return crypto
    .createHmac('sha256', String(secret))
    .update('mg-lead-exchange:zoho-watch:v1')
    .digest('hex')
    .slice(0, 48);
}

function verifyZohoWatchToken(provided, secret) {
  if (!provided || !secret) return false;
  // Accept the original direct-token form so an already-active channel made
  // with a <=50-character secret keeps working until the next renewal.
  return timingSafeEqual(String(provided), String(secret)) ||
    timingSafeEqual(String(provided), deriveZohoWatchToken(secret));
}

/**
 * The dealer's static webhook secret(s): its own WEBHOOK_SECRET and, for the
 * dealers it is scoped to, the shared FUSION_WEBHOOK_SECRET.
 */
async function loadTokenSecrets(catalystApp, integration) {
  // getDecryptedCredential THROWS (CREDENTIAL_DECRYPT_FAILED) when the
  // stored ciphertext cannot be opened with the current
  // INTEGRATION_CREDENTIALS_KEY — e.g. after the key is rotated without
  // re-saving the credentials. Uncaught, that escaped verifyWebhook and
  // surfaced from the route as a 500 INTERNAL_ERROR, which reads like a
  // middleware outage rather than what it is: an authentication problem.
  // A failure to authenticate must always present as 401.
  let webhookSecret = null;
  let unreadable = false;
  try {
    webhookSecret = await integrationAuthService.getDecryptedCredential(
      catalystApp,
      integration.ROWID,
      'WEBHOOK_SECRET'
    );
  } catch (err) {
    logger.error(
      'webhookVerificationService',
      `Webhook secret for integration ${integration.ROWID} could not be decrypted — re-save it so it is encrypted with the current INTEGRATION_CREDENTIALS_KEY`,
      err
    );
    unreadable = true;
  }

  // The shared secret (env var) is accepted for the dealers it is explicitly
  // scoped to, alongside the dealer's own secret. It never applies to any
  // other dealer.
  const shared = getSharedWebhookConfig();
  const sharedApplies = Boolean(
    shared.secret && shared.dealerCodes.has(String(integration.dealer_code || '').toLowerCase())
  );
  const secrets = [webhookSecret, sharedApplies ? shared.secret : null].filter(Boolean);
  return { secrets, unreadable };
}

// Standard Webhooks (https://www.standardwebhooks.com), as Fusion SD
// documents them: refuse anything more than five minutes from now.
const STANDARD_WEBHOOK_TOLERANCE_SECONDS = 300;

/**
 * The HMAC key(s) a stored signing secret may stand for, as { form, key }.
 * `whsec_<base64>` is the Standard Webhooks form and is decoded. Fusion SD
 * issues it with its own prefix in front (`lapi_whsec_<base64>`, seen in its
 * 1Password connection details, 27 Oct 2026); the part after `whsec_` is
 * decoded the same way, and the whole string is still tried as given.
 * Without either prefix the encoding is unconfirmed (FUSION_REMEDIATION_PLAN
 * .md Q20), so the secret is tried as given and, when it is valid base64,
 * decoded too.
 */
function signingKeys(secret) {
  const text = String(secret || '').trim();
  if (!text) return [];
  if (text.startsWith('whsec_')) return [{ form: 'whsec', key: Buffer.from(text.slice('whsec_'.length), 'base64') }];
  const keys = [{ form: 'text', key: Buffer.from(text, 'utf8') }];
  const prefixed = /^[A-Za-z0-9]+_whsec_([A-Za-z0-9+/]+={0,2})$/.exec(text);
  if (prefixed && prefixed[1].length % 4 === 0) {
    keys.push({ form: 'prefixed-whsec', key: Buffer.from(prefixed[1], 'base64') });
  }
  if (/^[A-Za-z0-9+/]+={0,2}$/.test(text) && text.length % 4 === 0) {
    keys.push({ form: 'base64', key: Buffer.from(text, 'base64') });
  }
  // A hex secret (e.g. the 64-character shared one) is often used as the
  // bytes it encodes. Fusion's webhooks failed every form above on 23 Oct.
  if (/^[0-9a-fA-F]+$/.test(text) && text.length % 2 === 0 && text.length >= 32) {
    keys.push({ form: 'hex', key: Buffer.from(text, 'hex') });
  }
  return keys;
}

/**
 * For a signature that matched none of the accepted forms: which common
 * slip would have produced it, if any (a pasted label in front of the
 * secret, signing the body alone, the {timestamp}.{body} form). Diagnostic
 * only: these are never accepted. Returns a variant NAME, never key
 * material or body content.
 */
function diagnoseSignatureMismatch(secret, webhookId, timestamp, rawBody, provided) {
  const text = String(secret || '').trim();
  const body = Buffer.isBuffer(rawBody) ? rawBody : Buffer.from(String(rawBody), 'utf8');
  const keyVariants = [
    ['secret-as-text', Buffer.from(text, 'utf8')],
    ['secret-hex', /^[0-9a-fA-F]+$/.test(text) && text.length % 2 === 0 ? Buffer.from(text, 'hex') : null],
    ['note-label-prefix', Buffer.from(`FUSIONWEBHOOKSECRET=${text}`, 'utf8')],
    ['note-label-prefix-newline', Buffer.from(`FUSIONWEBHOOKSECRET=\n${text}`, 'utf8')],
    ['note-label-prefix-space', Buffer.from(`FUSIONWEBHOOKSECRET= ${text}`, 'utf8')],
    ['whsec-prefix-as-text', Buffer.from(`whsec_${text}`, 'utf8')],
  ].filter(([, key]) => key);
  const contentVariants = [
    ['id.timestamp.body', (h) => h.update(`${webhookId}.${timestamp}.`).update(body)],
    ['timestamp.body', (h) => h.update(`${timestamp}.`).update(body)],
    ['body-only', (h) => h.update(body)],
  ];
  for (const [keyName, key] of keyVariants) {
    for (const [contentName, feed] of contentVariants) {
      const hmac = feed(crypto.createHmac('sha256', key));
      const digest = hmac.digest();
      const asBase64 = digest.toString('base64');
      const asHex = digest.toString('hex');
      if (provided.some((sig) => timingSafeEqualBase64(sig, asBase64) || sig.toLowerCase() === asHex)) {
        return `${keyName}/${contentName}`;
      }
    }
  }
  return null;
}

// Standard Webhooks secrets are 24 to 64 random bytes; fewer than this is
// almost certainly a copy-and-paste slip.
const MIN_SIGNING_KEY_BYTES = 16;

/**
 * Why a signing secret an admin is saving cannot work, or null. Only the
 * whsec_<base64> form can be checked: its key must be valid base64 of at
 * least MIN_SIGNING_KEY_BYTES. A secret without the prefix is used as given
 * (its encoding is unconfirmed, Q20).
 */
function signingSecretProblem(secret) {
  const text = String(secret || '').trim();
  if (!text.startsWith('whsec_')) return null;
  const encoded = text.slice('whsec_'.length);
  if (!/^[A-Za-z0-9+/]+={0,2}$/.test(encoded) || encoded.length % 4 !== 0) {
    return 'The signing secret starts with whsec_ but what follows is not valid base64. Paste it exactly as Fusion issued it.';
  }
  if (Buffer.from(encoded, 'base64').length < MIN_SIGNING_KEY_BYTES) {
    return 'The signing secret is too short to be a Standard Webhooks secret. Paste it exactly as Fusion issued it.';
  }
  return null;
}

function signStandardWebhook(key, webhookId, timestamp, rawBody) {
  return crypto
    .createHmac('sha256', key)
    .update(`${webhookId}.${timestamp}.`)
    .update(Buffer.isBuffer(rawBody) ? rawBody : Buffer.from(String(rawBody), 'utf8'))
    .digest('base64');
}

function timingSafeEqualBase64(a, b) {
  const bufA = Buffer.from(String(a || ''), 'base64');
  const bufB = Buffer.from(String(b || ''), 'base64');
  if (bufA.length === 0 || bufA.length !== bufB.length) return false;
  return crypto.timingSafeEqual(bufA, bufB);
}

async function verifyStandardWebhook(catalystApp, integration, rawBody, headers) {
  const webhookId = String(headers['webhook-id'] || '');
  const timestampText = String(headers['webhook-timestamp'] || '').trim();
  if (!webhookId || !timestampText || !headers['webhook-signature']) return { ok: false, reason: 'MISSING_AUTH' };

  const timestamp = /^\d+$/.test(timestampText) ? Number(timestampText) : NaN;
  const now = Math.floor(Date.now() / 1000);
  if (!Number.isFinite(timestamp) || Math.abs(now - timestamp) > STANDARD_WEBHOOK_TOLERANCE_SECONDS) {
    return { ok: false, reason: 'STALE_TIMESTAMP' };
  }

  let signingSecret = null;
  try {
    signingSecret = await integrationAuthService.getDecryptedCredential(
      catalystApp,
      integration.ROWID,
      'WEBHOOK_SIGNING_SECRET'
    );
  } catch (err) {
    logger.error(
      'webhookVerificationService',
      `Webhook signing secret for integration ${integration.ROWID} could not be decrypted — re-save it so it is encrypted with the current INTEGRATION_CREDENTIALS_KEY`,
      err
    );
    return { ok: false, reason: 'WEBHOOK_SECRET_UNREADABLE' };
  }
  // The shared secret (FUSION_WEBHOOK_SECRET) is also accepted for the dealers
  // FUSION_WEBHOOK_DEALER_CODES scopes it to: we sent it to Fusion via
  // LastPass while some dealers store Fusion's own secret (27 Oct 2026).
  const shared = getSharedWebhookConfig();
  const sharedApplies = Boolean(
    shared.secret && shared.dealerCodes.has(String(integration.dealer_code || '').toLowerCase()) &&
    shared.secret !== String(signingSecret || '').trim()
  );
  const candidates = [
    ...signingKeys(signingSecret).map((k) => ({ ...k, source: 'dealer', secret: signingSecret })),
    ...(sharedApplies ? signingKeys(shared.secret).map((k) => ({ ...k, source: 'shared', secret: shared.secret })) : []),
  ];
  if (candidates.length === 0) {
    logger.error('webhookVerificationService', `No webhook signing secret configured for integration ${integration.ROWID}`);
    return { ok: false, reason: 'WEBHOOK_SIGNING_SECRET_MISSING' };
  }

  // Space-separated `v1,<base64>` entries: more than one while the dealer
  // rotates its secret. Any other version is ignored.
  const provided = String(headers['webhook-signature'])
    .split(' ')
    .filter((entry) => entry.startsWith('v1,'))
    .map((entry) => entry.slice(3));
  const matched = candidates.find(({ key }) => {
    const expected = signStandardWebhook(key, webhookId, timestampText, rawBody);
    return provided.some((signature) => timingSafeEqualBase64(signature, expected));
  });
  if (!matched) {
    // Safe to log: header shape, clock skew, body size and a variant name.
    // Never the secret, the signature value or the body.
    const header = String(headers['webhook-signature']);
    let wouldMatch = null;
    try { wouldMatch = diagnoseSignatureMismatch(signingSecret, webhookId, timestampText, rawBody, provided); } catch { wouldMatch = null; }
    const bodyBuffer = Buffer.isBuffer(rawBody) ? rawBody : Buffer.from(String(rawBody), 'utf8');
    logger.error('webhookVerificationService', `Signature mismatch for integration ${integration.ROWID}: ${JSON.stringify({
      // Lets Fusion and us find the same delivery; neither reveals the body.
      webhookId: webhookId.slice(0, 80),
      bodySha256: crypto.createHash('sha256').update(bodyBuffer).digest('hex').slice(0, 16),
      candidates: candidates.map(({ source, form }) => `${source}/${form}`),
      v1Entries: provided.length,
      otherEntries: header.split(' ').filter((entry) => entry && !entry.startsWith('v1,')).map((entry) => entry.split(',')[0].slice(0, 10)),
      signatureLengths: provided.map((sig) => sig.length),
      clockSkewSeconds: now - timestamp,
      bodyBytes: Buffer.isBuffer(rawBody) ? rawBody.length : Buffer.byteLength(String(rawBody)),
      wouldMatch: wouldMatch || 'none',
    })}`);
    return { ok: false, reason: 'INVALID_SIGNATURE' };
  }

  // A static token sent alongside must match as well (Q19). Fusion's own
  // webhooks carry only the signature headers.
  const tokenHeader = headers['x-webhook-token'] || headers['x-api-key'];
  if (tokenHeader) {
    const { secrets } = await loadTokenSecrets(catalystApp, integration);
    const tokenValid = secrets.some((secret) => timingSafeEqual(String(tokenHeader), secret));
    if (!tokenValid) return { ok: false, reason: 'INVALID_TOKEN' };
  }
  logger.info('webhookVerificationService', `Signature verified for integration ${integration.ROWID} with ${matched.source}/${matched.form}`);
  // The fingerprint of the secret that actually matched: the SLA return-channel
  // proof only counts a dealer's own stored secret (fusionReturnChannelProof).
  return {
    ok: true,
    method: 'STANDARD_WEBHOOKS',
    signingSecretFingerprint: signingSecretFingerprint(matched.secret),
  };
}

/**
 * @param {object} integration - dealer_integrations row
 * @param {Buffer|string} rawBody - the raw, unparsed request body (must be
 *   captured before JSON parsing — HMAC verification requires exact bytes)
 * @param {object} headers - lowercased request headers
 */
async function verifyWebhook(catalystApp, integration, rawBody, headers) {
  const webhookEnabled = !(
    integration.webhook_enabled === false || integration.webhook_enabled === 0 ||
    String(integration.webhook_enabled).toLowerCase() === 'false' ||
    String(integration.webhook_enabled) === '0'
  );
  if (!webhookEnabled) {
    return { ok: false, reason: 'WEBHOOK_DISABLED' };
  }

  if (ALLOW_INSECURE_WEBHOOKS) {
    logger.error(
      'webhookVerificationService',
      `ALLOW_INSECURE_WEBHOOKS is enabled for integration ${integration.ROWID}; use only in a local test environment.`
    );
    return { ok: true };
  }

  // Fusion SD signs its webhooks the Standard Webhooks way (Batch 5). Only
  // with FUSION_INBOUND_V2 on, every Fusion request must be signed. A static
  // token cannot replace the signed body and timestamp required by Q19.
  if (integration.crm_type === 'FUSION_SD' && isFusionInboundV2Enabled()) {
    return verifyStandardWebhook(catalystApp, integration, rawBody, headers);
  }

  const { secrets, unreadable } = await loadTokenSecrets(catalystApp, integration);

  if (secrets.length === 0) {
    if (unreadable) return { ok: false, reason: 'WEBHOOK_SECRET_UNREADABLE' };
    logger.error('webhookVerificationService', `No webhook secret configured for integration ${integration.ROWID}`);
    return { ok: false, reason: 'WEBHOOK_AUTH_NOT_CONFIGURED' };
  }

  // Preferred: HMAC signature in X-Signature / X-Webhook-Signature header.
  const signatureHeader = headers['x-webhook-signature'] || headers['x-signature'];
  if (signatureHeader) {
    const provided = signatureHeader.replace(/^sha256=/, '');
    const valid = secrets.some((secret) => timingSafeEqual(computeHmac(secret, rawBody), provided));
    return valid ? { ok: true } : { ok: false, reason: 'INVALID_SIGNATURE' };
  }

  // Static token in X-Webhook-Token (or X-Api-Key). Catalyst's own gateway
  // treats any "Authorization: Bearer ..." header as a Catalyst OAuth token
  // and rejects the call (401 INVALID_TOKEN) BEFORE this function runs, so a
  // dealer CRM cannot use the Authorization header on a Catalyst endpoint.
  const tokenHeader = headers['x-webhook-token'] || headers['x-api-key'];
  if (tokenHeader) {
    const valid = secrets.some((secret) => timingSafeEqual(String(tokenHeader), secret));
    return valid ? { ok: true } : { ok: false, reason: 'INVALID_TOKEN' };
  }

  // Fallback: shared bearer token in Authorization header.
  const authHeader = headers['authorization'];
  if (authHeader) {
    const token = authHeader.replace(/^Bearer\s+/i, '');
    const valid = secrets.some((secret) => timingSafeEqual(token, secret));
    return valid ? { ok: true } : { ok: false, reason: 'INVALID_TOKEN' };
  }

  // Zoho CRM Notification API echoes the configured watch token in the
  // JSON notification body rather than an HTTP auth header.
  try {
    const parsed = JSON.parse(Buffer.isBuffer(rawBody) ? rawBody.toString('utf8') : String(rawBody));
    if (parsed?.token) {
      const valid = secrets.some((secret) => verifyZohoWatchToken(parsed.token, secret));
      return valid ? { ok: true } : { ok: false, reason: 'INVALID_TOKEN' };
    }
  } catch {
    // Invalid JSON is reported by the route after authentication checks.
  }

  return { ok: false, reason: 'MISSING_AUTH' };
}

module.exports = {
  verifyWebhook,
  signStandardWebhook,
  signingSecretProblem,
  computeHmac,
  deriveZohoWatchToken,
  verifyZohoWatchToken,
};
